// Command genstubs 从 OpenAPI 规范生成尚未实现的 operation 列表。
//
// 用法（在 backend-go 目录）：
//
//	go run ./tools/genstubs
//
// 实现某个模块后，把 handler 加进 internal/api/server.go 的 implemented()，
// 生成的文件不需要改。
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

type spec struct {
	Paths map[string]map[string]json.RawMessage `json:"paths"`
}

var httpMethods = map[string]bool{
	"get": true, "post": true, "put": true, "patch": true,
	"delete": true, "head": true, "options": true,
}

func main() {
	specPath := flag.String("spec", "../docs/api/openapi.json", "OpenAPI 规范路径")
	outPath := flag.String("out", "internal/api/stubs_gen.go", "输出文件")
	flag.Parse()

	raw, err := os.ReadFile(*specPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "read spec: %v\n", err)
		os.Exit(1)
	}
	var parsed spec
	if err := json.Unmarshal(raw, &parsed); err != nil {
		fmt.Fprintf(os.Stderr, "parse spec: %v\n", err)
		os.Exit(1)
	}

	var patterns []string
	for path, operations := range parsed.Paths {
		for method := range operations {
			if !httpMethods[strings.ToLower(method)] {
				continue
			}
			patterns = append(patterns, strings.ToUpper(method)+" "+path)
		}
	}
	sort.Strings(patterns)

	var body strings.Builder
	body.WriteString("// Code generated by tools/genstubs from docs/api/openapi.json; DO NOT EDIT.\n\n")
	body.WriteString("package api\n\n")
	body.WriteString("// stubOps 是规范里还没有 Go 实现的 operation。\n")
	body.WriteString("var stubOps = []string{\n")
	for _, pattern := range patterns {
		fmt.Fprintf(&body, "\t%q,\n", pattern)
	}
	body.WriteString("}\n")

	formatted, err := format.Source([]byte(body.String()))
	if err != nil {
		fmt.Fprintf(os.Stderr, "format: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*outPath, formatted, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "write: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("wrote %d operations to %s\n", len(patterns), *outPath)
}
